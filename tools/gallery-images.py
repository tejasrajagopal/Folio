#!/usr/bin/env python3
"""Turns exported gallery PNGs into the site's project galleries.

  python3 tools/gallery-images.py <source-dir>

<source-dir> holds one folder per project (river/, avant/, …) with PNGs named in gallery order (01.png, 02.png, …).
For each image it writes, into works/<project>/:  NN.jxl + NN.webp at full size and NN-s.jxl + NN-s.webp at half size
(JPEG XL is the main format; WebP is the fallback for browsers that can't decode JPEG XL yet). It also writes
src/js/galleries.js, the list the project view reads (file, size and shape of every image).
Needs ffmpeg built with libjxl, and Pillow.
"""
import json, os, subprocess, sys
from PIL import Image

SRC, ROOT = sys.argv[1], os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
JXL_DISTANCE, JXL_EFFORT, WEBP_QUALITY = '1.6', '8', 80        # distance 1.0 ≈ visually lossless; 1.6 is a touch smaller

def jxl(src_png, out):
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src_png, '-c:v', 'libjxl', '-distance', JXL_DISTANCE, '-effort', JXL_EFFORT, out], check=True)

galleries, total = {}, {'jxl': 0, 'webp': 0, 'png': 0}
for project in sorted(os.listdir(SRC)):
    pdir = os.path.join(SRC, project)
    if not os.path.isdir(pdir): continue
    out = os.path.join(ROOT, 'works', project); os.makedirs(out, exist_ok=True)
    items = []
    for f in sorted(x for x in os.listdir(pdir) if x.endswith('.png')):
        n, path = f[:-4], os.path.join(pdir, f)
        im = Image.open(path).convert('RGB'); w, h = im.size
        ratio = w / h
        kind = 'tall' if ratio < 1 else 'wide' if w >= 2000 else 'half'      # full-width, portrait, or half-width landscape
        small = im.resize((round(w / 2), round(h / 2)), Image.LANCZOS)
        tmp = os.path.join(out, '_tmp.png')
        for suffix, img in (('', im), ('-s', small)):
            img.save(tmp); jxl(tmp, os.path.join(out, f'{n}{suffix}.jxl'))
            img.save(os.path.join(out, f'{n}{suffix}.webp'), 'WEBP', quality=WEBP_QUALITY, method=6)
        os.remove(tmp)
        total['png'] += os.path.getsize(path)
        for ext in ('jxl', 'webp'): total[ext] += os.path.getsize(os.path.join(out, f'{n}.{ext}')) + os.path.getsize(os.path.join(out, f'{n}-s.{ext}'))
        items.append({'n': n, 'w': w, 'h': h, 'kind': kind})
        print(f'{project}/{n}  {w}x{h}  {kind:4}  jxl {os.path.getsize(os.path.join(out, n + ".jxl"))//1024:5d} KB  webp {os.path.getsize(os.path.join(out, n + ".webp"))//1024:5d} KB')
    galleries[project] = items

with open(os.path.join(ROOT, 'src', 'js', 'galleries.js'), 'w') as f:
    f.write('  // generated by tools/gallery-images.py: the images of each project gallery, in order (files in works/<project>/)\n')
    f.write('  const GALLERIES = ' + json.dumps(galleries, separators=(',', ':')) + ';\n')
mb = lambda b: f'{b/1e6:.1f} MB'
print(f"\nsource PNG {mb(total['png'])} → JPEG XL {mb(total['jxl'])} (both sizes), WebP fallback {mb(total['webp'])} (both sizes)")
